// Helper to compute ISO dates dynamically relative to now
const now = new Date();
const addDays = (days: number, hours = 0) => {
  const d = new Date(now.getTime() + days * 86400000 + hours * 3600000);
  return d.toISOString();
};
const subDays = (days: number, hours = 0) => {
  const d = new Date(now.getTime() - days * 86400000 - hours * 3600000);
  return d.toISOString();
};

